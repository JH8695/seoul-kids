import assert from 'node:assert/strict';
import { parseDetailSchedule, parseDetailWeekdays } from '../scripts/schedule.mjs';

const W = (title, s, e) => ({ title, classStart: `${s}T00:00:00+09:00`, classEnd: `${e}T00:00:00+09:00` });
const dates = (detail, w) => parseDetailSchedule(detail, w).dates;

// 1) "운영일 : 17일,24일(토)" — 월은 제목의 "/10월" 에서 (사이트 이용기간은 10/17~10/24)
assert.deepEqual(
  dates('프로그램명 : 정원에서 배우다 - 주제 ; 씨앗의 비밀을 배우다 - 운영일 : 17일,24일(토)/14시~15시30분 - 인원 : 12명', W('(매헌시민의숲)(토,오후)정원에서 배우다/10월', '2026-09-25', '2026-10-24')),
  ['2026-10-17', '2026-10-24'],
);

// 2) "운영일정 : 10월 토, 일" → 요일
const gwang = '* 운영일정 : 10월 토, 일 * 운영시간 : 오전 : 10시30분~ 12시 오후 : 14시 ~ 15시30분 * 만나는 장소 : 아차산 어울림정원 광장';
assert.deepEqual(parseDetailWeekdays(gwang), [0, 6]);
assert.equal(dates(gwang, W('광진구숲해설-가족주말(서울형정원처방)(10월)', '2026-10-04', '2026-10-31')), null);

// 3) "10월 6, 13, 27일 (화요일)"
assert.deepEqual(
  dates('운영일시 : 2026년 10월 6, 13, 27일 (화요일) / 10시 30분 (30~40분)', W('[월드컵공원] 꽁지 불빛 반딧불이 해설(10월)', '2026-09-28', '2026-10-27')),
  ['2026-10-06', '2026-10-13', '2026-10-27'],
);

// 4) 표의 회차 줄 (HTML 태그를 뗀 뒤라 "17 일" 처럼 띄어질 수 있음)
const table = '수업일시 1회차 씩 진행되는 원데이 클래스입니다. 회차 수업일시 강의내용 1 10월 17 일(토) 14:00~15:20 특종 발견해 글 써보기 1,000원 2 10월 24일(토) 14:00~15:20 특종 발견해 글 써보기 1,000원 3 10월 31일(토) 14:00~15:20 특종 발견해 글 써보기 1,000원';
assert.deepEqual(dates(table, W('문화실험공간 호수 [월간 호수랩 10월] <특종! 호수 기자단>', '2026-10-17', '2026-10-31')), ['2026-10-17', '2026-10-24', '2026-10-31']);

// 5) "운영시간: 매일 화~토" (휴관 안내는 제외)
const sewer = 'ㅇ신청대상: 6세 이상 어린이 ~ 일반 성인 ㅇ운영시간: 매일 화~토 *일요일 오후 해설은 2월부터 운영 ㅇ 1월1일, 설날, 추석 명절 당일, 매주 월요일은 휴관이며';
assert.deepEqual(parseDetailWeekdays(sewer), [2, 3, 4, 5, 6]);

// ---- 날짜로 오인하면 안 되는 것들 ----
const w = W('체험 10월', '2026-10-01', '2026-10-31');
assert.equal(dates('접수기간 : 10월 23일 마감, 신청은 선착순', w), null); // 접수·마감 근처
assert.equal(dates('수업 신청은 10월 20일까지 해 주세요', w), null);
assert.equal(dates('우리 센터는 10월 20일에 새로 문을 열었어요', w), null); // 요일·시간·운영일 단서 없음
// 적힌 요일과 실제 요일이 다르면 못 믿음 (10월 18일은 일요일)
assert.equal(dates('운영일 : 10월 18일(토)', w), null);
assert.deepEqual(dates('운영일 : 10월 18일(일)', w), ['2026-10-18']);
// 이용 기간 밖의 날짜는 제외
assert.equal(dates('운영일 : 12월 5일(토)', w), null);
// "월간", "일정 변경" 같은 낱말의 글자를 요일로 보지 않음
assert.equal(parseDetailWeekdays('운영일정 : 월간 프로그램입니다'), null);
assert.equal(parseDetailWeekdays('아무 설명'), null);
// 슬래시 날짜는 요일이 같이 있을 때만
assert.deepEqual(dates('수업은 10/17(토), 10/24(토)에 있습니다', w), ['2026-10-17', '2026-10-24']);
assert.equal(dates('가격은 10/17 로 변경', w), null);

// ---- 실제 샘플에서 나온 사례 ----
// 접수 기간 안내("8월 25일 10시~ 9월 28일 17시")의 끝점을 운영일로 보지 않음
assert.deepEqual(
  dates('- 접수일시 : 2026년 8월 25일 10시~ 9월 28일 17시 - 모집대상 : 누구나 운영일시 : 2026년 10월 6, 13, 27일 (화요일) / 10시 30분', W('[월드컵공원] 반딧불이 해설(10월)', '2026-09-28', '2026-10-27')),
  ['2026-10-06', '2026-10-13', '2026-10-27'],
);
// 운영 기간 표현("3월 15일 부터 10월 25일")은 날짜 목록이 아님
assert.equal(dates('■ 운영일시 : 주말프로그램 운영 2026년 3월 15일 부터 2026년 10월 25일 시작시간(오후 2시)을 준수해 주세요', W('미니솟대만들기(매주 일)', '2026-03-09', '2026-10-25')), null);
assert.equal(dates('운영 : 10월 17일 ~ 10월 24일', w), null);
// 이용 기간이 오래된 데이터라도 요일이 맞는 해만 인정 (2024년 10월 10일은 목요일, 2026년은 토요일)
assert.deepEqual(
  dates('활동일 -10월 10일(토) 09:00~10:00 -10월 10일(토) 10:00~11:00 활동인원 : 회당 20명', W('[한강생태체험교실] 자연미술관', '2024-10-01', '2026-10-31')),
  ['2026-10-10'],
);

// ---- 이번에 확인한 실제 페이지들 ----
const P = parseDetailSchedule;

// 송파책박물관: 매주 토요일, 휴강 9/26 · 10/3 · 10/10 → 휴강일은 운영일이 아니라 쉬는 날
const songpa = '▶ 교육기간 : 2026. 9. 5. (토) ~ 11. 28. (토) / 매주 토요일 1일 2회 운영 - 1회차 : 14:00 – 14:50 (※ 보호자 포함 12팀) - 2회차 : 15:00 – 15:50 (※ 보호자 포함 12팀) ※ 1,2회차 교육 내용은 동일합니다. ※ 휴강 안내 : 9월 26일, 10월 3일, 10일 ▶ 교육 장소 : 송파책박물관 1층 키즈 스튜디오 ▶ 교육 대상 : 6-7세 유아와 보호자 ▶ 접수기간 : 2026. 8 . 21. (금) ~ 11. 27. (금)';
let r = P(songpa, W('[송파책박물관] [유아(6-7세] 요리조리, 우리는 책 요리사! (9~11월)', '2026-09-05', '2026-11-28'));
assert.equal(r.dates, null); // 9/26 을 운영일로 읽지 않음
assert.deepEqual(r.closedDates, ['2026-09-26', '2026-10-03', '2026-10-10']);
assert.ok(r.sources.some((x) => x.includes('휴강')));

// 우장산(난임부부): "토요일 2,3주", "8월제외"
const woojang = '***6월~11월 <헤아림, 토닥정원애 들다> 프로그램** ***8월제외*** 구분 프로그램명 요일 및 시간 대상자 개인 헤아림, 토닥정원애 들다 토요일 2,3주 오전 10시~12시 1년 이상 정상적인 부부생활을 했음에도 임신이 되지 않은 부부 (난임부부) ○ 참여대상 : 난임부부 ○ 모집정원 : 10명';
r = P(woojang, W('우장산 녹색복지센터 (6월~11월) 헤아림 , 토닥정원애 들다 (난임부부)', '2026-05-25', '2026-11-21'));
assert.deepEqual(r.weekOfMonth, [2, 3]);
assert.deepEqual(r.weekdays, [6]);
assert.deepEqual(r.excludeMonths, [8]);
assert.equal(r.dates, null);

// 아리수나라: "휴관일 : 매주 월요일" 은 쉬는 요일 → 월요일을 뺀 나머지 요일에 운영
const arisu = '* 예약 가능월 : 예약가능월은 3월에는 4월말까지 * 예약방법 : 서울시 공공서비스예약 * 예약 취소 발생 시 현장대기자 명단 순으로 입장이 가능합니다. * 휴관일 : 매주 월요일, 1월 1일, 설날 및 추석 연휴 * 문의 : 02-3146-5946(아리수나라 안내데스크)';
r = P(arisu, W('아리수나라 어린이 체험 예약', '2024-07-01', '2026-11-30'));
assert.deepEqual(r.weekdays, [0, 2, 3, 4, 5, 6]);
assert.equal(r.dates, null);
assert.deepEqual(r.closedDates, ['2026-01-01']);

// 휴관 안내 앞의 "몇째 주 요일"은 운영이 아님
r = P('운영시간 10시~17시 휴관일 : 매월 첫째 주 월요일', W('전시관 안내', '2026-10-01', '2026-10-31'));
assert.equal(r.weekOfMonth, null);

console.log('schedule.test.mjs OK');
